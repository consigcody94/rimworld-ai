/**
 * Should the colony be in the food phase? With hysteresis, so it stops flipping.
 *
 * Every journal showed the phase changing between "food" and "house" about once a minute: a pawn
 * at 27% food eats a stack of berries, reads 50%, the phase flips to building, and an hour later
 * it flips back. Each flip re-narrated a "new objective" to the stream. Entering the food phase
 * keeps the old thresholds; leaving it now needs a real margin.
 */
export function wantsFoodPhase({ hungriest, supply, earlyBaseNeeded, inFoodPhase }) {
  const enter = hungriest < 0.28 || (hungriest < 0.45 && supply < 0.3) ||
    (!earlyBaseNeeded && (hungriest < 0.45 || supply < 1.5));
  if (!inFoodPhase) return enter;
  return hungriest < 0.38 || (hungriest < 0.55 && supply < 0.5) ||
    (!earlyBaseNeeded && (hungriest < 0.55 || supply < 2.0));
}

