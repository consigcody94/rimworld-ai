/**
 * Which kind of weapon the colony's ideoligion wants, read from the pawn's own thoughts.
 *
 * With Ideology active a random start can despise ranged or melee weapons. One founder carried a
 * despised short bow for nine days: "Used despised weapon" and "Wielding a short bow" were minus
 * ten mood between them, every day, on a pawn that broke at thirty. The thought names the problem;
 * this reads it. Returns "melee", "ranged" or null.
 */
export function weaponPreferenceFromThoughts(thoughts = [], currentWeapon = null) {
  const despised = thoughts.map(String).some((t) => /despised weapon/i.test(t));
  if (!despised || !currentWeapon) return null;
  return isRangedWeapon(currentWeapon) ? "melee" : "ranged";
}
